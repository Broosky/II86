// The gamma curve compensates for the nonlinear response of human vision, producing a more perceptually linear brightness
// progression. The lookup tables are calculated for a gamma value of 2.2.
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t gammaCorrectedFormula(uint8_t ubPwm, float fGamma) {
  return (uint8_t)(255.0f * pow((float)ubPwm / 255.0f, fGamma) + 0.5f);
}
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t gammaCorrectedCondensed(uint8_t ubPwm) {
  return pgm_read_byte(&gammaCondensed[ubPwm]);
}
